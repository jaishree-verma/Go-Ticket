/**
 * Returns cities grouped alphabetically by starting letter A to Z.
 * If query is provided, filters cities before grouping.
 */
export const getGroupedCities = (query = '') => {
  const clean = (query || '').trim().toLowerCase();
  
  const filtered = clean
    ? ALL_CITIES_A_TO_Z.filter(
        c => c.city.toLowerCase().includes(clean) || c.state.toLowerCase().includes(clean)
      )
    : ALL_CITIES_A_TO_Z;

  const groups = {};
  filtered.forEach(item => {
    const letter = item.city.charAt(0).toUpperCase();
    if (!groups[letter]) groups[letter] = [];
    groups[letter].push(item);
  });

  return groups;
};
